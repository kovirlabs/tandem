// Writes ui/src/ipc/generated/index.ts re-exporting every ts-rs generated type.
import { readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const dir = fileURLToPath(new URL("../ui/src/ipc/generated/", import.meta.url));
const names = readdirSync(dir)
  .filter((f) => f.endsWith(".ts") && f !== "index.ts")
  .map((f) => f.slice(0, -3))
  .sort();
const body = names.map((n) => `export type { ${n} } from "./${n}";`).join("\n");
writeFileSync(`${dir}index.ts`, `// Generated by scripts/gen-ipc-index.mjs. Do not edit.\n${body}\n`);
console.log(`gen:ipc: ${names.length} types`);
